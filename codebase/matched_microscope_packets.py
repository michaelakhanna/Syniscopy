"""
Matched microscope packet utilities.

A matched packet stores one latent scene/trajectory state rendered under
multiple configured microscopes. A microscope is the comparison identity; its
contrast modality is backend metadata. The file format is a portable ``.npz``
bundle containing:

    - ``metadata_json``: JSON with latent state, microscope names, modality
      metadata, CRLB metadata, and annotation schema.
    - ``image__<microscope>`` arrays: one image per selected microscope.
    - ``fisher__<microscope>`` arrays: Fisher matrices per microscope when
      generated by the dataset packet workflow.
    - ``mask__<name>`` arrays: geometry/supported/ignore masks when generated by
      the dataset packet workflow.

Rendering is handled by the simulator/dataset workflow; this module owns the
portable packet contract and validation.
"""

from __future__ import annotations

